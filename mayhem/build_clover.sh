#!/usr/bin/env bash
#
# mayhem/build_clover.sh — build Clover's own config.plist and plist parsers on Linux (called by build.sh).
#
# Clover's "POSIX" build is the Xcode project Xcode/CloverConfigPlistValidator (the shipped config.plist
# validator). Its sources are compiled here with clang, unmodified, with a few force-included shim headers
# (mayhem/clover_shim) for the glibc-vs-macOS differences. OpenCorePkg is an empty git submodule in this
# checkout and the build is offline, so the handful of headers needed from it live in mayhem/vendor/.
#
# Two flavors of the same sources are built: the sanitized, SanCov-instrumented fuzz targets
# (fuzz_configplist, fuzz_plist + -standalone), and a normal-flags build (no sanitizer) of Clover's own
# CloverConfigPlistValidator main.cpp plus mayhem/clover_oracle/plist_dump.cpp, which mayhem/test.sh runs.
set -euo pipefail

: "${SANITIZER_FLAGS=-fsanitize=address,undefined -fno-sanitize-recover=all -fno-omit-frame-pointer}"
: "${DEBUG_FLAGS:=-g -gdwarf-3}"
: "${CC:=clang}" ; : "${CXX:=clang++}" ; : "${LIB_FUZZING_ENGINE:=-fsanitize=fuzzer}"
: "${MAYHEM_JOBS:=$(nproc)}"
: "${SRC:=/mayhem}"
cd "$SRC"

R=rEFIt_UEFI
OCP=mayhem/vendor/OpenCorePkg
CLV="$SRC/mayhem/build/clover"
mkdir -p "$CLV/obj" "$CLV/obj-normal" "$CLV/gen/x/y" mayhem/vendor/x/y
[ -e "$CLV/gen/Version.h" ] || : > "$CLV/gen/Version.h"   # generated by Clover's Xcode build phase; contents unused here

# Efi.h includes "../../OpenCorePkg/Include/..." relative to itself; -Imayhem/vendor/x/y resolves that to mayhem/vendor/OpenCorePkg.
INC=(-I"$CLV/gen/x/y" -Imayhem/vendor/x/y -Imayhem/clover_shim -IXcode/CloverConfigPlistValidator/src -IPosixCompilation/UefiMock
     -IPosixCompilation/CloverMock/Include -IInclude -IIntelFrameworkPkg/Include -IUefiCpuPkg/Include
     -I$OCP/Include/Apple -I$OCP/Include/Intel -I$OCP/Include/Acidanthera -I$OCP
     -IMdePkg/Include -IMdePkg/Include/X64 -IMdePkg/Include/Register/Intel -IMdeModulePkg/Include
     -I$R/PlatformPOSIX -I$R/PlatformPOSIX/include -I$R/include)
# -fno-sized-deallocation + PlatformEFI/cpp_util/operatorNewDelete.cpp: Clover's own operator new/delete are
# AllocatePool/FreePool (here malloc/free), which is what its `delete` of pool memory relies on.
# -fshort-wchar: UEFI CHAR16 is 16 bit. SIZE_T_MAX: macOS limits.h has it, glibc does not.
DEFS=(-DSIZE_T_MAX=SIZE_MAX -DJCONST=const -DNO_DEBUG_TRACE -DOC_TARGET_DEBUG)
# fuzzer-no-link: SanCov-instrument Clover's own code. -fno-sanitize-recover: halting UBSan, as everywhere.
# The "normal" flavor (the functional oracle) has neither the sanitizers nor SanCov.
CF_COMMON=(-fshort-wchar -fno-sized-deallocation -w -MD "${DEFS[@]}" "${INC[@]}" -include Platform.h)
CF_FUZZ=($SANITIZER_FLAGS $DEBUG_FLAGS -fsanitize=fuzzer-no-link "${CF_COMMON[@]}")
CF_NORMAL=($DEBUG_FLAGS "${CF_COMMON[@]}")

COMMON_CPP=(
  $R/Settings/ConfigPlist/Config_GUI.cpp $R/cpp_foundation/XBuffer.cpp $R/cpp_lib/XmlLiteCompositeTypes.cpp
  $R/cpp_lib/XmlLiteSimpleTypes.cpp $R/cpp_foundation/XString.cpp $R/Settings/ConfigPlist/ConfigPlistAbstract.cpp
  $R/Platform/b64cdecode.cpp $R/cpp_lib/XmlLiteUnionTypes.cpp $R/Settings/ConfigPlist/SMBIOSPlist.cpp
  $R/cpp_lib/XmlLiteArrayTypes.cpp $R/Settings/ConfigPlist/Config_ACPI_DSDT.cpp PosixCompilation/xcode_utf_fixed.cpp
  $R/cpp_lib/XmlLiteDictTypes.cpp $R/PlatformPOSIX/posix/abort.cpp $R/cpp_foundation/unicode_conversions.cpp
  $R/Platform/VersionString.cpp $R/Platform/guid.cpp $R/Platform/platformdata.cpp
  $R/Settings/ConfigPlist/Config_Quirks.cpp $R/cpp_lib/XmlLiteParser.cpp $R/cpp_foundation/XRBuffer.cpp
  $R/cpp_foundation/XStringArray.cpp $R/PlatformPOSIX/BootLog.cpp $R/Platform/Utils.cpp
  $R/PlatformPOSIX/BasicIO.cpp $R/Platform/plist/xml.cpp Xcode/CloverConfigPlistValidator/src/Platform.cpp
  $R/Platform/CloverVersion.cpp $R/cpp_lib/MemoryTracker.cpp $R/PlatformEFI/cpp_util/operatorNewDelete.cpp mayhem/clover_shim/operator_delete.cpp
)
PLIST_CPP=(
  $R/Platform/plist/plist.cpp $R/Platform/plist/base64.cpp $R/Platform/plist/TagArray.cpp $R/Platform/plist/TagBool.cpp
  $R/Platform/plist/TagData.cpp $R/Platform/plist/TagDate.cpp $R/Platform/plist/TagDict.cpp
  $R/Platform/plist/TagFloat.cpp $R/Platform/plist/TagInt64.cpp $R/Platform/plist/TagKey.cpp
  $R/Platform/plist/TagString8.cpp $R/libeg/FloatLib.cpp
)
PLIST_C=(Xcode/cpp_tests/src/BaseLib.c)   # AsciiStrDecimalToUintn() & co, from Clover's own cpp_tests mock

objname() { echo "$OBJ/$(echo "$1" | tr / _).o"; }

# select_flavor fuzz|normal: sets the object directory and compile flags used by objname/compile_one.
select_flavor() {
  if [ "$1" = fuzz ]; then OBJ="$CLV/obj"; CF=("${CF_FUZZ[@]}"); else OBJ="$CLV/obj-normal"; CF=("${CF_NORMAL[@]}"); fi
}

compile_one() {   # <kind> <src>; kind: cpp | c | ccpp (C source built as C++)
  local kind="$1" s="$2" o; o=$(objname "$s")
  case "$kind" in
    cpp)  $CXX -std=c++17 "${CF[@]}" -c "$s" -o "$o" ;;
    ccpp) $CXX -std=c++17 -x c++ "${CF[@]}" -c "$s" -o "$o" ;;
    # printf_lite.c passes &valist where va_list is an array on x86-64: only its __APPLE__ branch
    # (va_list by value) is correct there. __APPLE__ also selects mach timestamp code, switched off in the shim conf.
    baselib) $CXX -std=c++17 -x c++ -D__APPLE__ "${CF[@]}" -include mayhem/clover_shim/baselib_cxx.h -c "$s" -o "$o" ;;
    cplain) $CC "${CF[@]}" -c "$s" -o "$o" ;;
    c)    $CC -D__APPLE__ "${CF[@]}" -c "$s" -o "$o" ;;
  esac
}

compile_all() {   # <harness sources...>: every shared source plus the given extra C++ drivers
  local JOBS=() j pids=() pid
  for s in "${COMMON_CPP[@]}" "${PLIST_CPP[@]}" "$@"; do
    JOBS+=("cpp $s")
  done
  JOBS+=("baselib ${PLIST_C[0]}" "ccpp PosixCompilation/UefiMock/Library/BaseMemoryLib.c" "ccpp PosixCompilation/UefiMock/Library/DebugLib.c" "ccpp PosixCompilation/UefiMock/Library/MemoryAllocationLib.c" "c Library/MemLogLibDefault/printf_lite.c")
  for j in "${JOBS[@]}"; do
    while [ "$(jobs -rp | wc -l)" -ge "$MAYHEM_JOBS" ]; do wait -n || exit 1; done
    compile_one $j &
    pids+=($!)
  done
  for pid in "${pids[@]}"; do wait "$pid" || exit 1; done   # a failed compile must fail the build
}

# common objects = everything but the harnesses and the plist tag library
common_objs() {
  for s in "${COMMON_CPP[@]}" PosixCompilation/UefiMock/Library/MemoryAllocationLib.c Library/MemLogLibDefault/printf_lite.c; do objname "$s"; done
}
plist_objs() { for s in "${PLIST_CPP[@]}"; do objname "$s"; done; }
lib_objs() { for s in "${PLIST_C[@]}" PosixCompilation/UefiMock/Library/BaseMemoryLib.c PosixCompilation/UefiMock/Library/DebugLib.c; do objname "$s"; done; }

# ---- sanitized fuzz targets -------------------------------------------------------------------------------
select_flavor fuzz
compile_all mayhem/fuzz_configplist/harness.cpp mayhem/fuzz_plist/harness.cpp

$CXX $SANITIZER_FLAGS $DEBUG_FLAGS -c mayhem/lsan_off.cc -o "$CLV/lsan_off.o"
$CC  $SANITIZER_FLAGS $DEBUG_FLAGS -c "$STANDALONE_FUZZ_MAIN" -o "$CLV/standalone_main.o"

link_target() {   # <name> <objs...>
  local n="$1"; shift
  $CXX $SANITIZER_FLAGS $DEBUG_FLAGS "$@" "$CLV/lsan_off.o" $LIB_FUZZING_ENGINE -o "$SRC/$n"
  $CXX $SANITIZER_FLAGS $DEBUG_FLAGS "$@" "$CLV/lsan_off.o" "$CLV/standalone_main.o" -o "$SRC/$n-standalone"
}
link_target fuzz_configplist "$(objname mayhem/fuzz_configplist/harness.cpp)" $(common_objs) $(lib_objs)
link_target fuzz_plist "$(objname mayhem/fuzz_plist/harness.cpp)" $(common_objs) $(lib_objs) $(plist_objs)

# ---- normal-flags oracle binaries (run by mayhem/test.sh) -----------------------------------------------------
# clover-config-validator is Clover's own validator, unmodified: it runs ConfigPlistClass::parse and prints
# every parser message. clover-plist-dump runs ParseXML and prints the parsed top-level tags.
select_flavor normal
VALIDATOR_MAIN=Xcode/CloverConfigPlistValidator/src/main.cpp
compile_all "$VALIDATOR_MAIN" mayhem/clover_oracle/validator_globals.cpp mayhem/clover_oracle/plist_dump.cpp
$CXX $DEBUG_FLAGS "$(objname "$VALIDATOR_MAIN")" "$(objname mayhem/clover_oracle/validator_globals.cpp)" $(common_objs) $(lib_objs) -o "$CLV/clover-config-validator"
$CXX $DEBUG_FLAGS "$(objname mayhem/clover_oracle/plist_dump.cpp)" $(common_objs) $(lib_objs) $(plist_objs) -o "$CLV/clover-plist-dump"
